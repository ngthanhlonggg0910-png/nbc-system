-- =========================================================
-- THIRTEENTH-MONTH SALARY POLICY
-- =========================================================
-- One company policy per year, with optional employee overrides.
-- Intentionally contains no seed/demo data.

BEGIN;

CREATE TABLE IF NOT EXISTS payroll_thirteenth_month_policies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_year INTEGER NOT NULL UNIQUE,
  default_coefficient NUMERIC(6, 3) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  notes TEXT NULL,
  published_at TIMESTAMPTZ NULL,
  created_by VARCHAR(50) NULL REFERENCES employees(staff_id) ON DELETE SET NULL,
  updated_by VARCHAR(50) NULL REFERENCES employees(staff_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT ck_thirteenth_month_policy_year
    CHECK (policy_year BETWEEN 2000 AND 2100),
  CONSTRAINT ck_thirteenth_month_policy_coefficient
    CHECK (default_coefficient BETWEEN 0 AND 5),
  CONSTRAINT ck_thirteenth_month_policy_status
    CHECK (status IN ('draft', 'published'))
);

CREATE TABLE IF NOT EXISTS payroll_thirteenth_month_overrides (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  policy_id BIGINT NOT NULL
    REFERENCES payroll_thirteenth_month_policies(id) ON DELETE CASCADE,
  staff_id VARCHAR(50) NOT NULL
    REFERENCES employees(staff_id) ON DELETE RESTRICT,
  coefficient NUMERIC(6, 3) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  created_by VARCHAR(50) NULL REFERENCES employees(staff_id) ON DELETE SET NULL,
  updated_by VARCHAR(50) NULL REFERENCES employees(staff_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT uq_thirteenth_month_override_employee
    UNIQUE (policy_id, staff_id),
  CONSTRAINT ck_thirteenth_month_override_coefficient
    CHECK (coefficient BETWEEN 0 AND 5),
  CONSTRAINT ck_thirteenth_month_override_reason
    CHECK (LENGTH(TRIM(reason)) >= 3)
);

CREATE INDEX IF NOT EXISTS idx_thirteenth_month_override_staff
  ON payroll_thirteenth_month_overrides (staff_id, policy_id);

COMMIT;
