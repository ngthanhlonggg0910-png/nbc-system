--
-- Foundation =========================================================
-- E0.1 — PAYROLL ORGANIZATION for enterprise payroll filtering/drill-down
-- by work location, factory, branch, office, warehouse, etc.
--
-- This migration:
--   1. Creates work_locations.
--   2. Adds employees.work_location_id.
--   3. Adds required foreign keys/indexes.
--
-- This migration DOES NOT:
--   - Seed organization data.
--   - Assign employees to locations.
--   - Modify payroll statuses.
--   - Modify payslips.
-- =========================================================


-- ---------------------------------------------------------
-- 1. WORK LOCATION MASTER
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS work_locations (
  id BIGINT
    GENERATED BY DEFAULT AS IDENTITY
    PRIMARY KEY,

  code VARCHAR(50)
    NOT NULL
    UNIQUE,

  name VARCHAR(255)
    NOT NULL,

  location_type VARCHAR(30)
    NOT NULL,

  parent_id BIGINT NULL,

  is_active BOOLEAN
    NOT NULL
    DEFAULT TRUE,

  created_at TIMESTAMPTZ
    NOT NULL
    DEFAULT CURRENT_TIMESTAMP,

  updated_at TIMESTAMPTZ
    NOT NULL
    DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT ck_work_locations_type
    CHECK (
      location_type IN (
        'company',
        'head_office',
        'factory',
        'branch',
        'warehouse',
        'other'
      )
    ),

  CONSTRAINT ck_work_locations_not_self_parent
    CHECK (
      parent_id IS NULL
      OR parent_id <> id
    ),

  CONSTRAINT fk_work_locations_parent
    FOREIGN KEY (parent_id)
    REFERENCES work_locations(id)
    ON DELETE SET NULL
);


-- ---------------------------------------------------------
-- 2. ORGANIZATION INDEXES
-- ---------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_work_locations_parent
  ON work_locations(parent_id);

CREATE INDEX IF NOT EXISTS idx_work_locations_type_active
  ON work_locations(location_type, is_active);


-- ---------------------------------------------------------
-- 3. EMPLOYEE → WORK LOCATION
-- ---------------------------------------------------------

ALTER TABLE employees
  ADD COLUMN IF NOT EXISTS work_location_id BIGINT NULL;


DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'fk_employees_work_location'
      AND conrelid = 'employees'::regclass
  ) THEN
    ALTER TABLE employees
      ADD CONSTRAINT fk_employees_work_location
      FOREIGN KEY (work_location_id)
      REFERENCES work_locations(id)
      ON DELETE SET NULL;
  END IF;
END
$$;


-- ---------------------------------------------------------
-- 4. DOCUMENTATION
-- ---------------------------------------------------------

COMMENT ON TABLE work_locations IS
  'Master table for company work locations such as offices, factories, branches and warehouses.';

COMMENT ON COLUMN employees.work_location_id IS
  'Current work location assigned to the employee.';
