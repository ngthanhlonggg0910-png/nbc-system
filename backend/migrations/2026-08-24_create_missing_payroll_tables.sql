CREATE TABLE IF NOT EXISTS payroll_feedbacks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payslip_id BIGINT NOT NULL,
  staff_id VARCHAR(20) NOT NULL,
  category VARCHAR(50) NULL,
  content TEXT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  attachment_url TEXT NULL,
  handled_by VARCHAR(20) NULL,
  handled_at TIMESTAMPTZ NULL,
  resolved_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT fk_payroll_feedbacks_payslip
    FOREIGN KEY (payslip_id)
    REFERENCES employee_payslips(id)
    ON DELETE CASCADE,

  CONSTRAINT fk_payroll_feedbacks_staff
    FOREIGN KEY (staff_id)
    REFERENCES employees(staff_id),

  CONSTRAINT fk_payroll_feedbacks_handler
    FOREIGN KEY (handled_by)
    REFERENCES employees(staff_id),

  CONSTRAINT ck_payroll_feedbacks_status
    CHECK (status IN ('pending', 'reviewing', 'accepted', 'rejected', 'adjusted', 'resolved'))
);

CREATE INDEX IF NOT EXISTS idx_payroll_feedbacks_staff
  ON payroll_feedbacks(staff_id, status);

CREATE TABLE IF NOT EXISTS payroll_imports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name VARCHAR(255) NOT NULL,
  file_type VARCHAR(20) NOT NULL DEFAULT 'excel',
  mime_type VARCHAR(100) NULL,
  file_checksum VARCHAR(128) NULL,
  total_rows INTEGER NOT NULL DEFAULT 0,
  valid_rows INTEGER NOT NULL DEFAULT 0,
  invalid_rows INTEGER NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'validated',
  payroll_period_id BIGINT NULL,
  uploaded_by VARCHAR(20) NULL,
  committed_by VARCHAR(20) NULL,
  committed_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT fk_payroll_imports_period
    FOREIGN KEY (payroll_period_id)
    REFERENCES payroll_periods(id)
    ON DELETE SET NULL,

  CONSTRAINT fk_payroll_imports_uploader
    FOREIGN KEY (uploaded_by)
    REFERENCES employees(staff_id),

  CONSTRAINT fk_payroll_imports_committer
    FOREIGN KEY (committed_by)
    REFERENCES employees(staff_id),

  CONSTRAINT ck_payroll_imports_status
    CHECK (status IN ('validated', 'committed', 'failed', 'cancelled'))
);

CREATE INDEX IF NOT EXISTS idx_payroll_imports_status
  ON payroll_imports(status, created_at DESC);
