-- =========================================================
-- MIGRATION: Đồng bộ schema tổ chức/vai trò cho nhánh main
-- =========================================================
-- Bổ sung:
--   1. roles.id (BIGINT, sequence, UNIQUE) - code mới join theo roles.id
--   2. departments, job_titles (seed từ dữ liệu text hiện có)
--   3. employees.role_id / department_id / job_title_id + FK + backfill
-- An toàn: chỉ ADD COLUMN/IF NOT EXISTS, giữ nguyên cột text cũ.
-- =========================================================

-- ---------------------------------------------------------
-- 1. roles.id
-- ---------------------------------------------------------
ALTER TABLE roles ADD COLUMN IF NOT EXISTS id BIGINT;

CREATE SEQUENCE IF NOT EXISTS roles_id_seq OWNED BY roles.id;

UPDATE roles SET id = nextval('roles_id_seq') WHERE id IS NULL;

SELECT setval('roles_id_seq', GREATEST((SELECT COALESCE(MAX(id), 0) FROM roles), 1));

ALTER TABLE roles ALTER COLUMN id SET DEFAULT nextval('roles_id_seq');
ALTER TABLE roles ALTER COLUMN id SET NOT NULL;

ALTER TABLE roles DROP CONSTRAINT IF EXISTS roles_id_unique;
ALTER TABLE roles ADD CONSTRAINT roles_id_unique UNIQUE (id);

-- ---------------------------------------------------------
-- 2. departments & job_titles
-- ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS departments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT departments_name_key UNIQUE (name)
);

INSERT INTO departments (name)
SELECT DISTINCT btrim(e.department)
FROM employees e
WHERE e.department IS NOT NULL AND btrim(e.department) <> ''
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS job_titles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT job_titles_name_key UNIQUE (name)
);

INSERT INTO job_titles (name)
SELECT DISTINCT btrim(e.position)
FROM employees e
WHERE e.position IS NOT NULL AND btrim(e.position) <> ''
ON CONFLICT (name) DO NOTHING;

-- ---------------------------------------------------------
-- 3. employees: thêm cột + backfill + FK
-- ---------------------------------------------------------
ALTER TABLE employees ADD COLUMN IF NOT EXISTS role_id BIGINT;
ALTER TABLE employees ADD COLUMN IF NOT EXISTS department_id BIGINT;
ALTER TABLE employees ADD COLUMN IF NOT EXISTS job_title_id BIGINT;

UPDATE employees e
SET role_id = r.id
FROM roles r
WHERE r.code = e.role AND e.role_id IS NULL;

UPDATE employees e
SET department_id = d.id
FROM departments d
WHERE d.name = btrim(e.department) AND e.department_id IS NULL;

UPDATE employees e
SET job_title_id = j.id
FROM job_titles j
WHERE j.name = btrim(e.position) AND e.job_title_id IS NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employees_role') THEN
    ALTER TABLE employees ADD CONSTRAINT fk_employees_role
      FOREIGN KEY (role_id) REFERENCES roles(id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employees_department') THEN
    ALTER TABLE employees ADD CONSTRAINT fk_employees_department
      FOREIGN KEY (department_id) REFERENCES departments(id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_employees_job_title') THEN
    ALTER TABLE employees ADD CONSTRAINT fk_employees_job_title
      FOREIGN KEY (job_title_id) REFERENCES job_titles(id);
  END IF;
END
$$;
