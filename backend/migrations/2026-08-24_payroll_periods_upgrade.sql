-- =========================================================
-- MIGRATION: Nâng cấp khung payroll_periods cho schema mới
-- =========================================================
-- Bảng rỗng nên chuyển PK từ month sang id (IDENTITY),
-- bổ sung period_code, và liên kết employee_payslips.payroll_period_id.
-- =========================================================

-- Gỡ FK cũ trỏ vào payroll_periods(month)
ALTER TABLE employee_payslips
  DROP CONSTRAINT IF EXISTS fk_payslip_period;

-- Chuyển PK sang id
ALTER TABLE payroll_periods
  ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE payroll_periods
  DROP CONSTRAINT IF EXISTS payroll_periods_pkey;

ALTER TABLE payroll_periods
  ADD CONSTRAINT payroll_periods_pkey PRIMARY KEY (id);

-- period_code duy nhất (code mới thao tác theo period_code)
ALTER TABLE payroll_periods ADD COLUMN IF NOT EXISTS period_code VARCHAR(30);

UPDATE payroll_periods SET period_code = btrim(month) WHERE period_code IS NULL;

ALTER TABLE payroll_periods ALTER COLUMN period_code SET NOT NULL;

ALTER TABLE payroll_periods DROP CONSTRAINT IF EXISTS payroll_periods_period_code_key;
ALTER TABLE payroll_periods
  ADD CONSTRAINT payroll_periods_period_code_key UNIQUE (period_code);

-- Liên kết payslip -> period theo id
ALTER TABLE employee_payslips
  ADD COLUMN IF NOT EXISTS payroll_period_id BIGINT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_payslip_period'
  ) THEN
    ALTER TABLE employee_payslips
      ADD CONSTRAINT fk_payslip_period
      FOREIGN KEY (payroll_period_id)
      REFERENCES payroll_periods(id);
  END IF;
END
$$;
